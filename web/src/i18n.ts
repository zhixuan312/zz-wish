export const DICTS: Record<Locale, Dict> = { zh, en };
export type { Dict };

export function detectLocale(): Locale {
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  return langs[0]?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

/** "2 h 15 min" / "2 小时 15 分钟"; with seconds when asked. */
export function fmtDuration(ms: number, t: Dict, withSeconds = false): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  const h = Math.floor(total / 3600), m = Math.floor((total % 3600) / 60), s = total % 60;
  const u = t.units, parts: string[] = [];
  if (h) parts.push(`${h} ${u.h}`);
  if (m) parts.push(`${m} ${u.m}`);
  if (withSeconds && s && h === 0) parts.push(`${s} ${u.s}`);
  if (!parts.length) return total === 0 ? `0 ${u.m}` : withSeconds ? `${s} ${u.s}` : u.lessThanMinute;
  return parts.join(' ');
}

export const fmtClock = (ms: number) => {
  const s = Math.max(0, Math.ceil(ms / 1000)), h = Math.floor(s / 3600), m = Math.floor((s % 3600) / 60), x = s % 60;
  const p = (v: number) => String(v).padStart(2, '0');
  return `${h}:${p(m)}:${p(x)}`;
};

export const fmtDateTime = (ts: number, locale: Locale) =>
  new Intl.DateTimeFormat(locale === 'zh' ? 'zh-CN' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' }).format(ts);

export function fmtDateRange(start: number, end: number | null, locale: Locale): string {
  const formatter = new Intl.DateTimeFormat(locale === 'zh' ? 'zh-CN' : 'en-GB', { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' });
  return end === null ? formatter.format(start) : formatter.formatRange(start, end);
}
